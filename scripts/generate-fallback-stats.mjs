/**
 * Generates a static fallback SVG for the GitHub stats card, rendered from a
 * real, manually-verified snapshot of CynthiaWahome's stats (gathered via an
 * authenticated `gh api` call, independent of GITHUB_STATS_TOKEN).
 *
 * Run this manually whenever the snapshot goes stale:
 *   node scripts/generate-fallback-stats.mjs
 *
 * The output SVG is tagged with an HTML comment and a data attribute so it's
 * identifiable as a fallback (not visible to visitors, but greppable/visible
 * in view-source or devtools) if the live endpoint is serving it.
 */
import { writeFileSync } from "fs";
import { renderStatsCard } from "../src/cards/stats.js";

// Snapshot gathered 2026-08-01 via `gh api` (search/commits, search/issues,
// users/CynthiaWahome, graphql viewer{}) — update the numbers below when
// regenerating, not the rendering logic.
const stats = {
  name: "CynthiaWahome",
  totalStars: 0,
  totalCommits: 3101,
  totalIssues: 325,
  totalPRs: 685,
  totalPRsMerged: 589,
  mergedPRsPercentage: Math.round((589 / 685) * 100),
  totalReviews: 221,
  totalOrganizations: 14,
  totalDiscussionsStarted: 0,
  totalDiscussionsAnswered: 0,
  contributedTo: 308,
  totalArticles: 40,
  publicGists: 23,
  forkedRepos: 78,
  rank: { level: "B", percentile: 40 },
};

const svg = renderStatsCard(stats, {
  show_icons: true,
  theme: "dark",
  title_color: "53F7AE",
  hide_border: true,
  include_all_commits: true,
  hide: ["stars", "discussions_started", "discussions_answered", "orgs"],
  number_format: "long",
  custom_title: "GitHub Stats",
});

const tagged = svg.replace(
  "</svg>",
  `<!-- FALLBACK SNAPSHOT: generated 2026-08-01, not live data --></svg>`,
);

writeFileSync(
  new URL("../public/fallback-stats.svg", import.meta.url),
  tagged,
);

const moduleSource = `// AUTO-GENERATED by scripts/generate-fallback-stats.mjs — do not hand-edit.
// Regenerate with: node scripts/generate-fallback-stats.mjs
export const FALLBACK_STATS_SVG = ${JSON.stringify(tagged)};
`;
writeFileSync(
  new URL("../src/common/fallbackStats.js", import.meta.url),
  moduleSource,
);

console.log("Wrote public/fallback-stats.svg and src/common/fallbackStats.js");
